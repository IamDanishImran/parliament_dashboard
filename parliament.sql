CREATE TABLE Registration (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_code VARCHAR(8) NOT NULL UNIQUE,
  description VARCHAR(25) NOT NULL,
  inserted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE Admin (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL UNIQUE,
  email VARCHAR(100) NOT NULL UNIQUE,
  ic VARCHAR(12) NOT NULL UNIQUE CHECK (length(ic) = 12 AND ic ~ '^[0-9]{12}$'),
  id_register BIGINT NOT NULL,
  FOREIGN KEY (id_register) REFERENCES Registration(id) ON DELETE RESTRICT,
  inserted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE Dun (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL UNIQUE,
  email VARCHAR(100) NOT NULL UNIQUE,
  ic VARCHAR(12) NOT NULL UNIQUE CHECK (length(ic) = 12 AND ic ~ '^[0-9]{12}$'),
  id_register BIGINT NOT NULL,
  FOREIGN KEY (id_register) REFERENCES Registration(id) ON DELETE RESTRICT,
  inserted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE Admin_Dun (
  id_admin BIGINT NOT NULL,
  id_dun BIGINT NOT NULL,
  PRIMARY KEY (id_admin, id_dun),
  FOREIGN KEY (id_admin) REFERENCES Admin(id) ON DELETE CASCADE,
  FOREIGN KEY (id_dun) REFERENCES Dun(id) ON DELETE CASCADE,
  inserted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE Email (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(100) NOT NULL,
  complaint TEXT NOT NULL,
  status VARCHAR(50) DEFAULT 'PENDING' CHECK (UPPER(status) IN ('PENDING', 'COMPLETE')),
  id_dun BIGINT NOT NULL,
  FOREIGN KEY (id_dun) REFERENCES Dun(id) ON DELETE CASCADE,
  inserted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE Form (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notes TEXT NOT NULL,
  category TEXT NOT NULL,
  category_type TEXT NOT NULL,
  quantity INT NOT NULL,
  price DECIMAL(10, 2) NOT NULL,
  address VARCHAR(50) NOT NULL,
  phone VARCHAR(50) NOT NULL,
  help_type VARCHAR(50) CHECK (help_type IN ('TUNAI', 'BANTUAN PERALATAN', 'PERALANTAN DAN TUNAI')),
  item VARCHAR(50) NOT NULL,
  form_status VARCHAR(50) DEFAULT 'MOHON' CHECK (form_status IN ('MOHON', 'LULUS', 'DITOLAK', 'KIV')),
  id_dun BIGINT NOT NULL,
  FOREIGN KEY (id_dun) REFERENCES Dun(id) ON DELETE CASCADE,
  inserted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE Stats_Monthly (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month INT NOT NULL CHECK (month >= 1 AND month <= 12),
  year INT NOT NULL CHECK (year >= 2000 AND year <= extract(year from now())),
  total_form INT DEFAULT 0,
  id_form BIGINT NOT NULL,
  FOREIGN KEY (id_form) REFERENCES Form(id) ON DELETE CASCADE,
  inserted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE (month, year)
);

CREATE TABLE Form_Admin (
  id_admin BIGINT NOT NULL,
  id_form BIGINT NOT NULL,
  PRIMARY KEY (id_admin, id_form),
  FOREIGN KEY (id_admin) REFERENCES Admin(id) ON DELETE CASCADE,
  FOREIGN KEY (id_form) REFERENCES Form(id) ON DELETE CASCADE,
  inserted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);
